#!/usr/bin/env node
// Feature and release records for Tributary. Sources are delivery/features/<task-id>.smd and
// delivery/releases/<version>.smd; each has a rendered .md beside it, and delivery/README.md indexes them,
// so the records read well on GitHub.
//
//   feature <task-id>                  create the feature record from the roadmap task (no-op if it exists)
//   progress <task-id> [--json]        ticked capabilities, as "3 of 5 (60%)"
//   list [--json]                      every feature record with its status and progress
//   render                             regenerate every .md copy and the index
//   check <task-id|version>            0 smd errors, no fill: comments, at least one item, .md copies current
//   finalize <task-id> --pr <url>      after the QA pass: status approved, delivery line, render
//   release <version> [--previous <v>] create the release record from delivered, unreleased features
//   shipped <version>                  after the user's go: release approved, its features marked with it
//   site <out-dir>                     styled HTML pages and an index page, for GitHub Pages
//
// Options: --root <dir> (default TRIBUTARY_DELIVERY, else <repo>/delivery), --roadmap <file> (default
// <repo>/docs/roadmap.smd). Exit codes: 0 ok, 1 check failed, 2 error.

import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const skillDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = path.resolve(skillDir, '..', '..', '..');
const smdScript = path.join(repoRoot, '.claude', 'skills', 'semantic-markdown-reader', 'scripts', 'smd.cjs');
const today = () => new Date().toLocaleDateString('en-CA');

const FEATURE_SECTION = 'Capabilities';
const RELEASE_SECTION = 'Shipping features';
const FEATURE_STATUS = { draft: 'In progress', review: 'In QA', approved: 'Delivered' };
const RELEASE_STATUS = { draft: 'In preparation', review: 'Awaiting approval', approved: 'Released' };
const GENERATED = 'Generated by .claude/skills/delivery-docs/scripts/docs.mjs. Edit the .smd source, then run its render command.';

class Failure extends Error {
  constructor(code, message) {
    super(message);
    this.code = code;
  }
}

function parseArgs(argv) {
  const options = { json: false };
  const positional = [];
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--json') options.json = true;
    else if (['--root', '--roadmap', '--pr', '--previous'].includes(arg)) options[arg.slice(2)] = argv[++i];
    else if (arg.startsWith('--')) throw new Failure(2, `Unknown option ${arg}`);
    else positional.push(arg);
  }
  options.root = path.resolve(options.root ?? process.env.TRIBUTARY_DELIVERY ?? path.join(repoRoot, 'delivery'));
  options.roadmap = path.resolve(options.roadmap ?? path.join(repoRoot, 'docs', 'roadmap.smd'));
  return { command: positional[0], arg: positional[1], options };
}

function smd(args) {
  const result = spawnSync(process.execPath, [smdScript, ...args], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  return { status: result.status, out: result.stdout, err: result.stderr };
}

function tasksOf(file) {
  const { status, out, err } = smd(['tasks', file, '--all', '--json']);
  if (status !== 0) throw new Failure(2, `smd tasks ${file} failed: ${(err || out).trim()}`);
  const parsed = JSON.parse(out.slice(out.search(/[[{]/)));
  return Array.isArray(parsed) ? parsed : parsed.tasks;
}

// ---------- front matter ----------

function frontMatter(text) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  const fields = {};
  for (const line of (match?.[1] ?? '').split(/\r?\n/)) {
    const field = /^([A-Za-z][\w-]*):\s*(.*)$/.exec(line);
    if (field) fields[field[1]] = field[2].replace(/^"(.*)"$/, '$1');
  }
  return fields;
}

function setField(text, key, value) {
  const match = /^---\r?\n([\s\S]*?)(\r?\n)---/.exec(text);
  if (!match) throw new Failure(2, 'document has no front matter');
  const line = `${key}: ${value}`;
  const pattern = new RegExp(`^${key}:.*$`, 'm');
  const body = pattern.test(match[1]) ? match[1].replace(pattern, line) : `${match[1]}${match[2]}${line}`;
  return `---${match[2]}${body}${match[2]}---${text.slice(match[0].length)}`;
}

const yamlText = (value) => JSON.stringify(value).slice(1, -1);

// ---------- records ----------

const featureFile = (root, id) => path.join(root, 'features', `${id}.smd`);
const releaseFile = (root, version) => path.join(root, 'releases', `${version}.smd`);
const renderedFile = (file) => file.replace(/\.smd$/, '.md');

function readExisting(file) {
  if (!existsSync(file)) throw new Failure(2, `${file} does not exist`);
  return readFileSync(file, 'utf8');
}

function fromTemplate(template, values) {
  const text = readFileSync(path.join(skillDir, 'templates', template), 'utf8');
  return Object.entries(values).reduce((result, [key, value]) => result.replaceAll(`__${key}__`, value), text);
}

function progress(file, section) {
  const tasks = tasksOf(file).filter((task) => task.section === section);
  const done = tasks.filter((task) => task.done).length;
  const percent = tasks.length === 0 ? 0 : Math.round((done * 100) / tasks.length);
  return { done, total: tasks.length, percent, text: `${done} of ${tasks.length} (${percent}%)` };
}

function records(root, kind) {
  const dir = path.join(root, kind);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => name.endsWith('.smd'))
    .sort((a, b) => a.localeCompare(b, 'en', { numeric: true }))
    .map((name) => {
      const file = path.join(dir, name);
      const section = kind === 'features' ? FEATURE_SECTION : RELEASE_SECTION;
      return { id: name.slice(0, -4), file, ...frontMatter(readFileSync(file, 'utf8')), progress: progress(file, section) };
    });
}

// ---------- rendering for GitHub ----------

const bar = (percent) => `${'▰'.repeat(Math.round(percent / 10))}${'▱'.repeat(10 - Math.round(percent / 10))}`;

function featureState(record) {
  return record.release ? `Released in ${record.release}` : (FEATURE_STATUS[record.status] ?? record.status);
}

function renderRecord(file, kind) {
  const exported = smd(['export', file, '--to', 'md']);
  if (exported.status !== 0) throw new Failure(2, `smd export ${file} failed: ${exported.err.trim()}`);
  const fields = frontMatter(readFileSync(file, 'utf8'));
  const body = exported.out
    .replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, '')
    .replace(/> \[!NOTE\]\r?\n> \*\*For agents[\s\S]*?(\r?\n\r?\n|$)/g, '')
    .trim();
  const counted = progress(file, kind === 'features' ? FEATURE_SECTION : RELEASE_SECTION);
  const state = kind === 'features' ? featureState(fields) : (RELEASE_STATUS[fields.status] ?? fields.status);
  const facts = [
    `**Status:** ${state}`,
    `**Progress:** ${bar(counted.percent)} ${counted.done} of ${counted.total} ${kind === 'features' ? 'capabilities' : 'features'}`,
    `**Updated:** ${fields.updated}`,
  ];
  if (fields.released) facts.push(`**Released:** ${fields.released}`);
  return `<!-- ${GENERATED} -->\n\n# ${fields.title}\n\n${facts.join(' · ')}\n\n${fields.summary ? `> ${fields.summary}\n\n` : ''}${body}\n`;
}

function renderIndex(root) {
  const features = records(root, 'features');
  const releases = records(root, 'releases');
  const lines = [
    `<!-- ${GENERATED} -->`,
    '',
    '# Delivery status',
    '',
    'What Tributary is building and shipping, in plain terms. Each feature record says what it makes possible, how far along it is, and whether it changes anything for existing users. A record appears here when its pull request merges; work in progress is visible on its open pull request.',
    '',
    '## Features',
    '',
  ];
  if (features.length === 0) lines.push('No features delivered yet.');
  else {
    lines.push('| Feature | Status | Progress | Release |', '| --- | --- | --- | --- |');
    for (const record of features) {
      lines.push(`| [${record.title}](features/${record.id}.md) | ${featureState(record)} | ${bar(record.progress.percent)} ${record.progress.percent}% | ${record.release || 'Not yet released'} |`);
    }
  }
  lines.push('', '## Releases', '');
  if (releases.length === 0) lines.push('No releases yet.');
  else {
    lines.push('| Release | Status | Date | Features |', '| --- | --- | --- | --- |');
    for (const record of releases) {
      lines.push(`| [${record.title}](releases/${record.id}.md) | ${RELEASE_STATUS[record.status] ?? record.status} | ${record.released || record.updated} | ${record.progress.total} |`);
    }
  }
  return `${lines.join('\n')}\n`;
}

function renderedOutputs(root) {
  const outputs = new Map();
  for (const kind of ['features', 'releases']) {
    for (const record of records(root, kind)) outputs.set(renderedFile(record.file), renderRecord(record.file, kind));
  }
  outputs.set(path.join(root, 'README.md'), renderIndex(root));
  return outputs;
}

function render({ root }) {
  const outputs = renderedOutputs(root);
  for (const [file, text] of outputs) writeFileSync(file, text);
  console.log(`rendered ${outputs.size} file(s) under ${root}`);
}

// ---------- HTML site for GitHub Pages ----------

// Links between records point at .html, and the page badge shows the business state ("Delivered")
// instead of smd's document status.
function exportHtml(source, target, state) {
  const exported = smd(['export', source, '--to', 'html', '-o', target]);
  if (exported.status !== 0) throw new Failure(2, `smd export ${source} failed: ${exported.err.trim()}`);
  const html = readFileSync(target, 'utf8')
    .replace(/href="((?!https?:|#|\/)[^"]*?)\.md(#[^"]*)?"/g, 'href="$1.html$2"')
    .replace(/(<span class="smd-doc-status[^"]*">)[^<]*(<\/span>)/, `$1${state}$2`);
  writeFileSync(target, html);
}

function withReleaseDate(text, released) {
  return released ? text.replace(/^(---\r?\n[\s\S]*?\r?\n---\r?\n)/, `$1\n**Released:** ${released}\n`) : text;
}

function site(outDir, { root }) {
  if (!outDir) throw new Failure(2, 'site needs an output folder');
  const out = path.resolve(outDir);
  const features = records(root, 'features');
  const releases = records(root, 'releases');
  for (const [kind, list] of [['features', features], ['releases', releases]]) {
    mkdirSync(path.join(out, kind), { recursive: true });
    for (const record of list) {
      const state = kind === 'features' ? featureState(record) : (RELEASE_STATUS[record.status] ?? record.status);
      const source = path.join(out, kind, `${record.id}.smd`);
      writeFileSync(source, withReleaseDate(readFileSync(record.file, 'utf8'), record.released));
      exportHtml(source, path.join(out, kind, `${record.id}.html`), state);
      rmSync(source);
    }
  }
  const featureRows = features.map(
    (record) => `| [${record.title}](features/${record.id}.html) | ${featureState(record)} | :progress{value=${record.progress.percent} basis=measured label="${record.progress.done}/${record.progress.total}"} | ${record.release || 'Not yet released'} |`,
  );
  const releaseRows = releases.map(
    (record) => `| [${record.title}](releases/${record.id}.html) | ${RELEASE_STATUS[record.status] ?? record.status} | ${record.released || record.updated} | ${record.progress.total} |`,
  );
  const index = [
    '---',
    'smd: 2',
    'title: Tributary delivery status',
    'summary: What Tributary is building and shipping. Each feature says what it makes possible, how far along it is, and whether it changes anything for existing users.',
    'status: approved',
    'owners: ["@release"]',
    `updated: ${today()}`,
    '---',
    '',
    'Features appear here when their pull request merges; work in progress is visible on its open pull request.',
    '',
    '## Features',
    '',
    ...(featureRows.length > 0 ? ['| Feature | Status | Progress | Release |', '| --- | --- | --- | --- |', ...featureRows] : ['No features delivered yet.']),
    '',
    '## Releases',
    '',
    ...(releaseRows.length > 0 ? ['| Release | Status | Date | Features |', '| --- | --- | --- | --- |', ...releaseRows] : ['No releases yet.']),
    '',
  ].join('\n');
  const indexSource = path.join(out, 'index.smd');
  writeFileSync(indexSource, index);
  exportHtml(indexSource, path.join(out, 'index.html'), 'Overview');
  rmSync(indexSource);
  writeFileSync(path.join(out, '.nojekyll'), '');
  console.log(`site: ${features.length} feature(s), ${releases.length} release(s) in ${out}`);
}

// ---------- commands ----------

function feature(id, options) {
  const file = featureFile(options.root, id);
  if (existsSync(file)) return console.log(`exists ${file}`);
  const task = tasksOf(options.roadmap).find((entry) => entry.id === id);
  if (!task) throw new Failure(2, `no task {#${id}} in ${options.roadmap}`);
  const plain = task.text.replaceAll('`', '');
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(
    file,
    fromTemplate('feature.smd', {
      ID: id,
      TITLE: yamlText(plain.split(/: | — /)[0].slice(0, 70)),
      SUMMARY: yamlText(plain),
      OWNER: task.assignees?.[0] ?? '@coder',
      PRIORITY: task.priority ?? 'P2',
      DATE: today(),
      TEXT: task.text,
    }),
  );
  console.log(`created ${file}`);
  render(options);
}

function list({ root, json }) {
  const rows = records(root, 'features');
  if (json) {
    return console.log(JSON.stringify(rows.map(({ id, title, status, release, pr, progress: p }) => ({ id, title, status, release, pr, ...p })), null, 2));
  }
  if (rows.length === 0) return console.log('no feature records');
  for (const row of rows) console.log(`${row.id.padEnd(12)} ${featureState(row).padEnd(18)} ${row.progress.text.padEnd(14)} ${row.title}`);
}

function check(target, { root }) {
  const isFeature = existsSync(featureFile(root, target));
  const file = isFeature ? featureFile(root, target) : releaseFile(root, target);
  const text = readExisting(file);
  const problems = [];
  const validation = smd(['validate', file]);
  const errors = /(\d+) error\(s\)/.exec(`${validation.out}${validation.err}`);
  if (!errors || errors[1] !== '0') problems.push(`smd validate reports errors:\n${`${validation.out}${validation.err}`.trim()}`);
  const leftovers = [...text.matchAll(/<!--\s*fill:/g)].length;
  if (leftovers > 0) problems.push(`${leftovers} fill: comment(s) left`);
  const counted = progress(file, isFeature ? FEATURE_SECTION : RELEASE_SECTION);
  if (counted.total === 0) problems.push(isFeature ? 'no capabilities listed' : 'no features listed');
  for (const [output, expected] of renderedOutputs(root)) {
    const actual = existsSync(output) ? readFileSync(output, 'utf8').replaceAll('\r\n', '\n') : null;
    if (actual !== expected) problems.push(`${path.relative(root, output)} is ${actual === null ? 'missing' : 'out of date'}; run the render command`);
  }
  console.log(`${path.relative(root, file)}: ${isFeature ? 'capabilities' : 'features'} ${counted.text}`);
  if (problems.length > 0) throw new Failure(1, problems.map((problem) => `- ${problem}`).join('\n'));
  console.log('check passed');
}

function finalize(id, options) {
  if (!options.pr) throw new Failure(2, 'finalize needs --pr <url>');
  const file = featureFile(options.root, id);
  let text = readExisting(file);
  for (const [key, value] of [['status', 'approved'], ['updated', today()], ['pr', JSON.stringify(options.pr)]]) text = setField(text, key, value);
  const number = /\/pull\/(\d+)/.exec(options.pr)?.[1];
  const line = `Delivered on ${today()} through [pull request #${number ?? '?'}](${options.pr}), merged after QA passed on its final commit.`;
  text = text.replace(/(## Delivery\r?\n)[\s\S]*$/, `$1\n${line}\n`);
  writeFileSync(file, text);
  const counted = progress(file, FEATURE_SECTION);
  console.log(`finalized ${file}: capabilities ${counted.text}`);
  if (counted.done < counted.total) console.log(`warning: ${counted.total - counted.done} capability(ies) left unticked`);
  render(options);
}

function release(version, options) {
  const file = releaseFile(options.root, version);
  if (existsSync(file)) return console.log(`exists ${file}`);
  const delivered = records(options.root, 'features').filter((record) => record.status === 'approved' && !record.release);
  const lines = delivered.map((record) => `- [x] [${record.title}](../features/${record.id}.md) {#ship-${record.id}}`);
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(
    file,
    fromTemplate('release.smd', {
      VERSION: version,
      PREVIOUS: options.previous ?? 'none',
      SUMMARY: `Tributary ${version}.`,
      DATE: today(),
      FEATURES: lines.length > 0 ? lines.join('\n') : '<!-- fill: no delivered, unreleased feature records were found; list the features in this release. -->',
    }),
  );
  console.log(`created ${file} with ${delivered.length} delivered feature(s)`);
  render(options);
}

function shipped(version, options) {
  const file = releaseFile(options.root, version);
  let text = readExisting(file);
  for (const [key, value] of [['status', 'approved'], ['updated', today()], ['released', today()]]) text = setField(text, key, value);
  writeFileSync(file, text);
  const ids = tasksOf(file)
    .filter((task) => task.section === RELEASE_SECTION && task.done)
    .map((task) => /features\/([^)]+)\.md/.exec(task.text)?.[1])
    .filter(Boolean);
  for (const id of ids) {
    const target = featureFile(options.root, id);
    if (existsSync(target)) writeFileSync(target, setField(readFileSync(target, 'utf8'), 'release', JSON.stringify(version)));
  }
  console.log(`release ${version} approved; marked ${ids.length} feature(s): ${ids.join(', ') || 'none'}`);
  render(options);
}

// ---------- main ----------

const usage = 'Usage: docs.mjs feature|progress|list|render|check|finalize|release|shipped|site [task-id|version|out-dir] [options]';
try {
  const { command, arg, options } = parseArgs(process.argv.slice(2));
  const required = () => {
    if (!arg) throw new Failure(2, usage);
    return arg;
  };
  if (command === 'feature') feature(required(), options);
  else if (command === 'progress') {
    const file = featureFile(options.root, required());
    readExisting(file);
    const counted = progress(file, FEATURE_SECTION);
    console.log(options.json ? JSON.stringify(counted) : `${arg}: ${counted.text}`);
  } else if (command === 'list') list(options);
  else if (command === 'render') render(options);
  else if (command === 'check') check(required(), options);
  else if (command === 'finalize') finalize(required(), options);
  else if (command === 'release') release(required(), options);
  else if (command === 'shipped') shipped(required(), options);
  else if (command === 'site') site(required(), options);
  else throw new Failure(2, usage);
} catch (error) {
  if (!(error instanceof Failure)) throw error;
  console.error(error.message);
  process.exit(error.code);
}
